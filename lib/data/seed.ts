// ───────────────────────────── Orders ─────────────────────────────
const itemFromProduct = (
  product: Product,
  variantIdx: number,
  size: string,
  qty: number,
): OrderItem => {
  const v = product.variants[variantIdx];
  return {
    productId: product.id,
    productName: product.name,
    productSlug: product.slug,
    collectionId: product.collectionId,
    variantId: v.id,
    colorName: v.colorName,
    colorHex: v.colorHex,
    size,
    quantity: qty,
    unitPrice: product.price,
    totalPrice: product.price * qty,
    imageUrl: v.images[0],
  };
};

const makeOrder = (
  i: number,
  customer: Customer,
  status: OrderStatus,
  paymentStatus: PaymentStatus,
  items: OrderItem[],
  daysAgo: number,
): Order => {
  const subtotal = items.reduce((s, it) => s + it.totalPrice, 0);
  const shippingFee = customer.country === "Ghana" ? 30 : 2500;
  const total = subtotal + shippingFee;
  return {
    id: `ORD-2026-${String(i).padStart(4, "0")}`,
    trackingNumber: `UNAP-${String(i).padStart(6, "0")}`,
    customerId: customer.id,
    customerName: `${customer.firstName} ${customer.lastName}`,
    customerEmail: customer.email,
    customerPhone: customer.phone,
    shippingAddress: customer.addresses[0],
    billingAddress: null,
    items,
    status,
    paymentStatus,
    paymentMethod: customer.country === "Ghana" ? "momo" : "card",
    paymentReference: paymentStatus === "paid" ? `TXN${1000000 + i}` : null,
    subtotal,
    shippingFee,
    discount: 0,
    discountCode: null,
    total,
    currency: customer.currency,
    notes: "",
    customerNote: i % 5 === 0 ? "Please pack discreetly." : "",
    carrier: [
      "shipped",
      "in_transit",
      "out_for_delivery",
      "delivered",
    ].includes(status)
      ? "DHL Express"
      : null,
    estimatedDelivery: ["shipped", "in_transit", "out_for_delivery"].includes(
      status,
    )
      ? days(daysAgo - 3)
      : null,
    shippedAt: [
      "shipped",
      "in_transit",
      "out_for_delivery",
      "delivered",
    ].includes(status)
      ? days(daysAgo - 1)
      : null,
    deliveredAt: status === "delivered" ? days(Math.max(0, daysAgo - 3)) : null,
    createdAt: days(daysAgo),
    updatedAt: days(Math.max(0, daysAgo - 1)),
  };
};

