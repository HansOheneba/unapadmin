const itemFromProduct = (
  product: Product,
  variantIdx: number,
  size: string,
  qty: number,
): OrderItem => {
  const v = product.variants[variantIdx];
  return {
    productId: product.id,
    productName: product.name,
    productSlug: product.slug,
    collectionId: product.collectionId,
    variantId: v.id,
    colorName: v.colorName,
    colorHex: v.colorHex,
    size,
    quantity: qty,
    unitPrice: product.price,
    totalPrice: product.price * qty,
    imageUrl: v.images[0],
  };
};

const deliveryTypeFor = (customer: Customer): DeliveryType => {
  const city = customer.city?.toLowerCase() ?? "";
  const region = customer.region?.toLowerCase() ?? "";
  if (city === "accra" || region.includes("greater accra")) {
    return "accra_inhouse";
  }
  return "outside_accra";
};

const makeOrder = (
  i: number,
  customer: Customer,
  status: OrderStatus,
  paymentStatus: PaymentStatus,
  items: OrderItem[],
  daysAgo: number,
): Order => {
  const subtotal = items.reduce((s, it) => s + it.totalPrice, 0);
  const shippingFee = customer.country === "Ghana" ? 30 : 45;
  const total = subtotal + shippingFee;
  const deliveryType = deliveryTypeFor(customer);
  const inhouse = deliveryType === "accra_inhouse";
  const outOnRoad = ["picked_up", "in_transit", "delivered"].includes(status);
  return {
    id: `ORD-2026-${String(i).padStart(4, "0")}`,
    trackingNumber: `UNAP-${String(i).padStart(6, "0")}`,
    customerId: customer.id,
    customerName: `${customer.firstName} ${customer.lastName}`,
    customerEmail: customer.email,
    customerPhone: customer.phone,
    shippingAddress: customer.addresses[0],
    billingAddress: null,
    items,
    status,
    paymentStatus,
    paymentMethod: customer.country === "Ghana" ? "momo" : "card",
    paymentReference: paymentStatus === "paid" ? `TXN${1000000 + i}` : null,
    subtotal,
    shippingFee,
    discount: 0,
    discountCode: null,
    total,
    currency: "GHS",
    notes: "",
    customerNote: i % 5 === 0 ? "Please pack discreetly." : "",
    deliveryType,
    riderId: null,
    riderNote: "",
    carrier: outOnRoad && inhouse ? "Unapologetic Riders" : null,
    estimatedDelivery: ["picked_up", "in_transit"].includes(status)
      ? days(daysAgo - 3)
      : null,
    shippedAt: null,
    pickedUpAt:
      inhouse && ["picked_up", "in_transit", "delivered"].includes(status)
        ? days(daysAgo - 0.8)
        : null,
    outForDeliveryAt:
      inhouse && ["in_transit", "delivered"].includes(status)
        ? days(daysAgo - 0.5)
        : null,
    deliveredAt: status === "delivered" ? days(Math.max(0, daysAgo - 3)) : null,
    failedAt: status === "returned" ? days(Math.max(0, daysAgo - 1)) : null,
    failureReason: status === "returned" ? "customer_unavailable" : null,
    deliveryAttempts: status === "returned" ? 2 : outOnRoad ? 1 : 0,
    returnVerifiedAt: null,
    createdAt: days(daysAgo),
    updatedAt: days(Math.max(0, daysAgo - 1)),
  };
};

